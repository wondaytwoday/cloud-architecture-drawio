#!/usr/bin/env python3
"""Build a model that shows every catalog icon and every relationship kind.

    python3 evals/gallery.py evals/fixtures/icon-gallery.model.json

Icons that must sit in a subnet are placed in a matching provider network.
The fixture is rebuilt from the catalog, so a new icon shows up automatically.
"""
import json
from pathlib import Path
import sys

BASE = Path(__file__).resolve().parents[1]
CATALOG = BASE/'cloud-architecture-drawio/assets/icon-catalog.json'
CARD_W, CARD_H, GAP, COLUMNS, LEFT, TOP = 176, 124, 40, 10, 30, 110
KINDS = ('traffic', 'egress', 'replication', 'dns', 'association', 'management')


def model():
    catalog = json.loads(CATALOG.read_text(encoding='utf-8'))
    free = sorted(k for k, v in catalog.items() if v.get('placement') != 'subnet') + ['generic', 'generic.user']
    hosted = sorted(k for k, v in catalog.items() if v.get('placement') == 'subnet')
    nodes = []
    for i, icon in enumerate(free):
        row, col = divmod(i, COLUMNS)
        nodes.append({'id': icon.replace('.', '-'), 'icon': icon, 'label': icon,
                      'detail': catalog.get(icon, {}).get('name', 'built-in'),
                      'x': LEFT+col*(CARD_W+GAP), 'y': TOP+row*(CARD_H+GAP), 'w': CARD_W, 'h': CARD_H})
    y = TOP+((len(free)+COLUMNS-1)//COLUMNS)*(CARD_H+GAP)+20
    containers, x = [], LEFT
    # Each subnet-hosted icon gets its own subnet: some, like Application Gateway,
    # must have their subnet to themselves.
    for provider in ('aws', 'azure', 'gcp'):
        mine = [icon for icon in hosted if icon.startswith(provider+'.')]
        if not mine:
            continue
        top = y+80 if provider == 'aws' else y+40
        width = len(mine)*(CARD_W+2*GAP+10)+30
        network = {'id': f'{provider}-net', 'kind': 'vnet' if provider == 'azure' else 'vpc', 'provider': provider,
                   'label': f'{provider} network', 'x': x, 'y': y, 'w': width, 'h': top-y+CARD_H+100}
        containers.append(network)
        parent = network['id']
        if provider == 'aws':
            containers.append({'id': 'aws-az', 'kind': 'az', 'label': 'AZ', 'parent': parent,
                               'x': x+10, 'y': y+40, 'w': width-20, 'h': CARD_H+130})
            parent = 'aws-az'
        for j, icon in enumerate(mine):
            sx = x+20+j*(CARD_W+2*GAP+10)
            subnet = f"{icon.replace('.', '-')}-subnet"
            containers.append({'id': subnet, 'kind': 'subnet', 'label': 'subnet', 'parent': parent,
                               'x': sx, 'y': top, 'w': CARD_W+2*GAP, 'h': CARD_H+50})
            nodes.append({'id': icon.replace('.', '-'), 'icon': icon, 'label': icon, 'detail': catalog[icon]['name'],
                          'parent': subnet, 'x': sx+GAP, 'y': top+40, 'w': CARD_W, 'h': CARD_H})
        x += width+GAP
    # One labelled pair of plain cards per relationship kind, three pairs a row.
    y = max(n['y']+n['h'] for n in nodes+containers)+60
    edges = []
    for i, kind in enumerate(KINDS):
        row, col = divmod(i, 3)
        x0, y0 = LEFT+col*(2*CARD_W+180+GAP), y+row*(CARD_H+GAP)
        for end, dx in (('from', 0), ('to', CARD_W+180)):
            nodes.append({'id': f'{kind}-{end}', 'icon': 'generic', 'label': f'{kind} {end}', 'x': x0+dx, 'y': y0, 'w': CARD_W, 'h': CARD_H})
        edges.append({'id': f'kind-{kind}', 'source': f'{kind}-from', 'target': f'{kind}-to', 'kind': kind, 'label': kind})
    bottom = max(n['y']+n['h'] for n in nodes+containers)
    width = max(LEFT*2+COLUMNS*(CARD_W+GAP), x+LEFT)
    return {'provider': 'multi', 'title': f'Icon gallery · {len(catalog)} catalog icons',
            'subtitle': 'Every catalog icon and relationship kind, rebuilt from the catalog',
            'width': width, 'height': bottom+120, 'containers': containers, 'nodes': nodes, 'edges': edges,
            'routing': {'clearance': 4}, 'notes': ['Generated by evals/gallery.py; review icon shapes and line styles here.']}


if __name__ == '__main__':
    target = Path(sys.argv[1]) if len(sys.argv) > 1 else BASE/'evals/fixtures/icon-gallery.model.json'
    target.write_text(json.dumps(model(), ensure_ascii=False, indent=2)+'\n', encoding='utf-8')
    print(target)
